class SupportProtocolSelector:
    def __init__(self, settings):
        """Выбирает каталог политик из policy_dir либо встроенного набора."""
        self.directory = Path(settings.policy_dir) if settings.policy_dir else DEFAULT_DIR

    def load_approved(self, key):
        """Читает YAML-протокол и возвращает его только с документированным статусом approved.

        Требует reviewed_by и approval_reference. При отсутствии файла или реквизитов
        возвращает None; само содержание на клиническую корректность не оценивает.
        """
        path = self.directory / "protocols" / f"{key}.yaml"
        if not path.exists():
            return None
        protocol = yaml.safe_load(path.read_text(encoding="utf-8"))
        if (
            protocol.get("clinical_review_status") != "approved"
            or not protocol.get("reviewed_by")
            or not protocol.get("approval_reference")
        ):
            return None
        return protocol

    def select(self, state):
        """Выбирает основной и послеродовой утверждённые протоколы; для urgent возвращает два None."""
        if state.safety_route == "urgent":
            return None, None
        return self.load_approved(state.support_protocol), self.load_approved(
            "postpartum_support"
        ) if state.postpartum else None

    def allowed_actions(self, state):
        """Собирает разрешённые действия и требования к текущему ответу.

        Учитывает обязательность рекомендации, её недавнее напоминание и допустимость
        добровольного предложения шкалы. Эти инструкции задаёт код по SupportState.
        """
        actions = [
            "выслушивание",
            "один уточняющий вопрос",
            "предложение реальной поддержки близких",
        ]
        if state.referral_required:
            lines = [
                "Обязательно предложи обратиться к врачу или квалифицированному специалисту: спокойно, без запугивания и без диагноза."
            ]
        elif state.recommend_specialist:
            lines = [
                "Обращение к специалисту уже рекомендовано недавно: не повторяй рекомендацию в каждом ответе, но поддержи, если она сама заговорит об этом."
            ]
        else:
            lines = []
        lines.append(
            "Не предлагай опросники и тесты самостоятельно: конкретное добровольное приглашение при необходимости добавит приложение."
        )
        lines.append(PRACTICAL_HELP.get(state.support_protocol, PRACTICAL_HELP["general_support"]))
        if state.has_voice_context:
            lines.append(
                "Голосовые наблюдения в patient_state.short.voice — предположения внешней модели "
                "об интонации, не симптомы, диагноз или тяжесть состояния. Они не доказывают "
                "печаль, тревогу, депрессию, опасность или улучшение. Слова и самоотчёт "
                "пользовательницы важнее. Не спорь с её объяснением и не связывай баллы шкал "
                "с интонацией. Исторические голосовые наблюдения не описывают текущую эмоцию."
            )
        if state.voice_clarification:
            lines.append(
                "В этой записи есть неуверенный голосовой сигнал "
                + ("печали" if state.voice_clarification == "sad" else "напряжения")
                + ". Уместен один бережный вопрос о том, как она сейчас себя чувствует "
                "или что её тяготит. Не утверждай эмоцию по голосу. Если она уже объяснила "
                "состояние, ответь на её слова и уточни только то, что поможет ей сейчас. "
                "Не добавляй второй вопрос и не навязывай обсуждение чувств при отказе."
            )
        if state.support_basis == "recent_observation_needs_confirmation":
            lines.append(
                "Тема поддержки выбрана по недавнему наблюдению, а не по текущему симптому: "
                "сначала коротко уточни, относится ли её просьба к тому, что она описывала. "
                "Не утверждай, что прежнее состояние продолжается."
            )
        elif state.support_basis == "screening_result_needs_confirmation":
            lines.append(
                "Направление поддержки выбрано по свежей самооценке в опроснике: "
                "уточни, что беспокоит сейчас. Результат шкалы не доказывает текущего "
                "состояния и не даёт диагноза."
            )
        if state.change in ("worsening", "mixed"):
            lines.append(
                "В текущей реплике есть ухудшение: уточни, что изменилось и мешает ли это обычным делам. Низкий прежний балл не опровергает новые слова. При выраженных трудностях поддержи обращение за очной помощью."
            )
        if state.change == "improving":
            lines.append(
                "Отметь улучшение и то, что помогло, если она сама об этом сказала. Улучшение не снимает автоматически прежние жалобы или необходимость обсуждения результата со специалистом."
            )
        if state.functional_impact:
            lines.append(
                "Есть влияние на повседневную жизнь: приоритет — доступная помощь и очная оценка; список упражнений или новая анкета не заменяют её."
            )
        if "physical_discomfort" in (*state.current_signals, *state.recent_signals):
            lines.append(
                "Есть текущая или недавняя телесная жалоба: не советуй прогулки, физическую нагрузку, дыхательные упражнения или объяснение симптома эмоциями. Недавнюю жалобу сначала уточни. Предложи обсудить актуальный симптом с врачом; срочные признаки требуют немедленной оценки."
            )
        if "possible_violence_exposure" in (*state.current_signals, *state.recent_signals):
            lines.append(
                "Сведения о насилии: сначала уточни безопасность разговора. Не советуй конфронтацию, совместную терапию или обращение к предполагаемому агрессору за поддержкой. Недавнее наблюдение сначала уточни, не выдавай за текущий факт."
            )
        if state.birth_trauma_followup:
            lines.append(
                "Есть результат шкалы переживаний после родов, требующий обсуждения: не проси подробно заново переживать роды, не проводи экспозицию/дебрифинг/EMDR в чате. Можно помочь найти слова для обращения к специалисту, работающему с перинатальной травмой."
            )
        if state.analysis_scope == "irrelevant":
            lines.append(
                "Полная классификация текущего сообщения пропущена как нерелевантная; это не доказательство отсутствия симптомов. Не начинай разбирать прежние эмоции без повода."
            )
        return lines + ["Разрешены: " + ", ".join(actions) + "."]

    def system_prompt(
        self, state, protocol, postpartum, support_contact="", address="ты", privacy_note=False
    ):
        """Собирает системные правила, перинатальный контекст и разрешённые действия.

        Добавляет только переданные утверждённые протоколы, выбранную форму обращения,
        правило псевдонимов и ограничения контактов. Личную историю сюда не включает:
        она передаётся отдельно как недоверенные данные.
        """
        base = (self.directory / "base_system_prompt.md").read_text(encoding="utf-8")
        stage = STAGE_LINES.get(state.perinatal_stage)
        if stage:
            week = (
                f", {state.gestational_week}-я неделя"
                if state.gestational_week is not None
                else f", {state.postpartum_weeks} нед. после родов"
                if state.postpartum_weeks is not None
                else ""
            )
            base += "\n" + stage.format(week=week)
        if protocol:
            base += "\nУтверждённый протокол:\n" + yaml.safe_dump(protocol, allow_unicode=True)
        if postpartum:
            base += "\nДополнительный контекст:\n" + yaml.safe_dump(postpartum, allow_unicode=True)
        contacts = (
            "Линию помощи можно назвать один раз, без нажима: "
            + support_contact
            + " Экстренные службы: 112, скорая 103. Других телефонов, сайтов и организаций не называй."
            if support_contact
            else "В этом ответе не называй телефонов, сайтов и организаций. Экстренные службы"
            " (112, 103) упоминай, только если она описывает опасность."
        )
        form = (
            "Обращайся на «вы»."
            if address == "вы"
            else "Обращайся на «ты», как в остальных сообщениях приложения; не переходи на «вы»."
        )
        privacy = (
            "\nЛичные данные в тексте заменены обозначениями в квадратных скобках ([ИМЯ_1],"
            " [ТЕЛЕФОН_1] и подобными). Используй их как обычные имена и не обсуждай сами обозначения."
            " Обозначения не склоняются: пиши их точно так, как они встретились, а если нужен"
            " другой падеж — назови человека по роли («с мужем», «врачу») вместо обозначения."
            if privacy_note
            else ""
        )
        return (
            base
            + "\n"
            + form
            + privacy
            + "\n"
            + contacts
            + "\n"
            + "\n".join(self.allowed_actions(state))
        )
