# Признаки, которые не понижаются пометкой «навязчивые мысли» (действие уже совершено).
_NOT_DOWNGRADED = {"self_harm_act", "harm_to_baby_act", "acute_medical", "violence_immediate"}
_DOWNGRADE = {
    "self_harm_intent": "self_harm_ideation",
    "harm_to_baby_intent": "harm_to_baby_thoughts",
}
# Перед симптомом: отрицание или страх симптома, а не сам симптом.
_NEGATED_BEFORE = re.compile(
    r"\b(?:нет|не было|без|никак\w+|не бывает|боюсь|страшно,? что будет|опасаюсь|читала про|читаю про|"
    r"что делать при|вдруг будет|на случай|из носа)\b[^,]{0,25}$"
)
_NEGATED_AFTER = re.compile(r"^[^,]{0,15}\b(?:нет|не было|не беспокоит|прошл[оаи]|из носа)\b")
_NEGATED_THOUGHTS = re.compile(
    r"\b(?:нет|не было|никогда не было|не возникает|не появля\w+)\b[^,]{0,25}\b(?:мысл|желани|намерени)|"
    r"\b(?:мысл\w+|желани\w+|намерени\w+)\b[^,]{0,40}\bнет\b|\bих (?:\w+ ){0,2}нет\b|не собираюсь"
)
_SYMPTOM_RISKS = {"acute_medical", "medical_symptom"}
_THOUGHT_RISKS = {"self_harm_ideation", "harm_to_baby_thoughts"}


@dataclass
class LexiconResult:
    route: str = NORMAL
    risks: list[str] = field(default_factory=list)


def normalize(text: str) -> str:
    """Приводит текст к нижнему регистру, заменяет ё и удаляет цитаты и прямую чужую речь."""
    text = text.lower().replace("ё", "е")
    text = _QUOTED.sub(" ", text)
    return _DIRECT_SPEECH.sub(" ", text)


def assess(text: str) -> LexiconResult:
    """Выбирает маршрут по словарным правилам и возвращает отсортированные коды рисков.

    Разбирает отдельные фразы, учитывая отрицания, давние события и нежелательные
    навязчивые мысли. Совпадение urgent имеет приоритет над рекомендацией;
    без совпадений возвращает normal. Отсутствие совпадения не подтверждает
    безопасность сообщения и не заменяет дальнейший анализ.
    """
    found: dict[str, str] = {}
    for clause in _CLAUSES.split(normalize(text)):
        if not clause or not clause.strip():
            continue
        distant_past = bool(_PAST.search(clause)) and not _PRESENT.search(clause)
        unwanted = bool(_UNWANTED.search(clause))
        for risk, (route, pattern) in RULES.items():
            match = pattern.search(clause)
            if not match:
                continue
            if risk in _SYMPTOM_RISKS and (
                _NEGATED_BEFORE.search(clause[: match.start()])
                or _NEGATED_AFTER.search(clause[match.end() :])
            ):
                continue
            if risk in _THOUGHT_RISKS and _NEGATED_THOUGHTS.search(clause) and not unwanted:
                continue
            if distant_past:
                # Давнее событие само по себе не является текущей опасностью; оценку продолжит Jev.
                continue
            if unwanted and risk in _DOWNGRADE and risk not in _NOT_DOWNGRADED:
                risk, route = _DOWNGRADE[risk], REFER
            found[risk] = URGENT if URGENT in (route, found.get(risk)) else route
    if not found:
        return LexiconResult()
    route = URGENT if URGENT in found.values() else REFER
    return LexiconResult(route=route, risks=sorted(found))
